def get_ci(data):
    """Computes 95% Confidence Interval via Standard Error of the Mean."""
    return 1.96 * sem(data)

def run_experiment_1(S=40):
    print(f"--- Running Exp 1: Approximation Error (S={S} Trials) ---")
    sigma = 1.5
    X_1d = torch.linspace(0.0, 5.0, 200, device=device).unsqueeze(1)
    X_3d = torch.tensor(qmc.Halton(d=3).random(200), dtype=torch.float32) * 3.0

    def exact_k(X):
        X_norm = (X**2).sum(1).view(-1, 1)
        sq_dist = X_norm + X_norm.t() - 2.0 * torch.mm(X, X.t())
        return torch.exp(-sq_dist / (2 * sigma**2))

    K_1d, K_3d = exact_k(X_1d), exact_k(X_3d)
    M_values, results = [5, 25, 50, 250, 500], []

    for M in M_values:
        errs = {'mc_1d': [], 'qmc_1d': [], 'mc_3d': [], 'qmc_3d': []}
        for s in range(S):
            Z_mc_1, _ = generate_rff_features(X_1d, M, sigma, False, seed=s)
            Z_qm_1, _ = generate_rff_features(X_1d, M, sigma, True, seed=s)
            Z_mc_3, _ = generate_rff_features(X_3d, M, sigma, False, seed=s)
            Z_qm_3, _ = generate_rff_features(X_3d, M, sigma, True, seed=s)

            errs['mc_1d'].append(torch.mean((K_1d - torch.mm(Z_mc_1, Z_mc_1.t()))**2).item())
            errs['qmc_1d'].append(torch.mean((K_1d - torch.mm(Z_qm_1, Z_qm_1.t()))**2).item())
            errs['mc_3d'].append(torch.mean((K_3d - torch.mm(Z_mc_3, Z_mc_3.t()))**2).item())
            errs['qmc_3d'].append(torch.mean((K_3d - torch.mm(Z_qm_3, Z_qm_3.t()))**2).item())

        results.append({
            'M': M,
            'MC MSE (1D)': f"{np.mean(errs['mc_1d']):.4f} ± {get_ci(errs['mc_1d']):.4f}",
            'QMC MSE (1D)': f"{np.mean(errs['qmc_1d']):.4f} ± {get_ci(errs['qmc_1d']):.4f}",
            'MC MSE (3D)': f"{np.mean(errs['mc_3d']):.4f} ± {get_ci(errs['mc_3d']):.4f}",
            'QMC MSE (3D)': f"{np.mean(errs['qmc_3d']):.4f} ± {get_ci(errs['qmc_3d']):.4f}"
        })
    return pd.DataFrame(results)

def run_experiment_2(S=40):
    print(f"\n--- Running Exp 2: RMSE Convergence (S={S} Trials) ---")
    N_values = [100, 500, 1000, 2000]
    envs = ["labor", "regulatory", "exponential", "groot", "multitask"]
    sigma_wF, sigma_wL, sigma_J = 0.1, 0.2, 0.05
    final_results = []

    for env in envs:
        dim = get_env_details(env)["dim"]
        bnd = get_env_details(env)["bounds"]
        print(f"Evaluating Environment: {env.upper()}")

        eval_grid = qmc.Halton(d=dim, scramble=True).random(n=50)
        for i in range(dim): eval_grid[:, i] = bnd[i][0] + eval_grid[:, i] * (bnd[i][1] - bnd[i][0])
        eval_grid_t = torch.tensor(eval_grid, dtype=torch.float32, device=device)

        # 2x2 Ablation: MC vs QMC, FMLP vs FKRR
        for use_qmc in [False, True]:
            samp_prefix = "QMC" if use_qmc else "MC"
            rmse_fkrr = {N: [] for N in N_values}
            rmse_fmlp = {N: [] for N in N_values}

            for trial in range(S):
                sampler = RKHS_Sampler(M=100, sigma=1.5, input_dim=dim, use_qmc=use_qmc)
                X_data, y_target, v_true = [], [], []

                for _ in range(max(N_values) + 200):
                    func = sampler.sample_function()
                    with torch.no_grad():
                        X_data.append(func(eval_grid_t).cpu().numpy().flatten())

                    wF_star = compute_argmax_constrained(func, env, device)

                    eps_F = np.random.normal(0, sigma_wF, dim)
                    wF_exec = np.clip(wF_star + eps_F, [b[0] for b in bnd], [b[1] for b in bnd])
                    wF_exec_t = torch.tensor(wF_exec, dtype=torch.float32, device=device).unsqueeze(0)

                    with torch.no_grad():
                        wL_clean = func(wF_exec_t).squeeze(0).item()
                        if env == "groot": wL_clean = np.clip(wL_clean, -1.0, 4.0)
                        wL_exec = wL_clean + np.random.normal(0, sigma_wL)
                        _, jL_exec = evaluate_objectives(env, wF_exec_t, torch.tensor([wL_exec], device=device))

                    y_target.append(jL_exec.item() + np.random.normal(0, sigma_J))
                    v_true.append(compute_true_baseline(env, func, wF_star, sigma_wF, sigma_wL, device))

                X_all, y_all, v_all = np.vstack(X_data), np.array(y_target), np.array(v_true)
                X_test, y_test_true = X_all[-200:], v_all[-200:]

                for N in N_values:
                    X_train, y_train = X_all[:N], y_all[:N]

                    # 1. Train and Evaluate FKRR
                    krr = KernelRidge(alpha=0.1, kernel='rbf', gamma=0.01)
                    krr.fit(X_train, y_train)
                    rmse_fkrr[N].append(root_mean_squared_error(y_test_true, krr.predict(X_test)))

                    # 2. Train and Evaluate FMLP
                    mlp = MLPRegressor(hidden_layer_sizes=(128, 64, 32), max_iter=200, random_state=trial)
                    mlp.fit(X_train, y_train)
                    rmse_fmlp[N].append(root_mean_squared_error(y_test_true, mlp.predict(X_test)))

            for N in N_values:
                final_results.append({
                    'Environment': env.capitalize(), 'Method': f"{samp_prefix}-FKRR", 'N': N,
                    'RMSE_Mean': np.mean(rmse_fkrr[N]), 'RMSE_CI': get_ci(rmse_fkrr[N])
                })
                final_results.append({
                    'Environment': env.capitalize(), 'Method': f"{samp_prefix}-FMLP", 'N': N,
                    'RMSE_Mean': np.mean(rmse_fmlp[N]), 'RMSE_CI': get_ci(rmse_fmlp[N])
                })

    return pd.DataFrame(final_results)

