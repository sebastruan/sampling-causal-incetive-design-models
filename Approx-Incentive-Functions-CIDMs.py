def get_env_details(env_name):
    """Returns domain bounds, input dimension, and problem type."""
    details = {
        "labor": {"dim": 1, "bounds": (0.0, 5.0), "is_cost": False},
        "regulatory": {"dim": 1, "bounds": (0.0, 10.0), "is_cost": False},
        "exponential": {"dim": 1, "bounds": (0.0, 2.0), "is_cost": False},
        "groot": {"dim": 1, "bounds": (0.0, 7.0), "is_cost": True},
        "multitask": {"dim": 3, "bounds": (0.0, 3.0), "is_cost": False}
    }
    return details[env_name]

def evaluate_objectives(env_name, wF, wL):
    """Returns objectives for autograd. For Groot, returns negative cost to maximize."""
    if env_name == "labor":
        return wL - 0.5 * (wF**2).sum(dim=-1), 3.0 * wF.sum(dim=-1) - wL
    elif env_name == "regulatory":
        return 5.0 * wF.sum(dim=-1) - wL, wL - (wF**2).sum(dim=-1)
    elif env_name == "exponential":
        return wL - torch.exp(wF.sum(dim=-1)), 5.0 * wF.sum(dim=-1) - wL
    elif env_name == "groot":
        wL_clamp = torch.clamp(wL, -1.0, 4.0)
        jf_cost = wL_clamp**2 + wF.sum(dim=-1)**2 - wL_clamp * wF.sum(dim=-1)
        jl_cost = (wF.sum(dim=-1) - 5.0)**2 + wL_clamp**2
        return -jf_cost, jl_cost
    elif env_name == "multitask":
        beta = torch.tensor([2.0, 1.5, 3.0], device=device)
        return wL - 0.5 * torch.sum(wF**2, dim=-1), torch.sum(wF * beta, dim=-1) - wL

def compute_argmax_constrained(f, env_name, device, res=2000):
    """Solves Follower's Best Response via Halton Grid Search + SciPy L-BFGS-B."""
    env = get_env_details(env_name)
    dim, bnd = env["dim"], env["bounds"]

    # 1. Quasi-random Grid Search
    halton = qmc.Halton(d=dim, scramble=True)
    grid_np = halton.random(n=res)
    grid_np = bnd[0] + grid_np * (bnd[1] - bnd[0])
    grid = torch.tensor(grid_np, dtype=torch.float32, device=device)

    with torch.no_grad():
        wL_grid = f(grid).squeeze(-1)
        if env_name == "groot": wL_grid = torch.clamp(wL_grid, -1.0, 4.0)
        jF_grid, _ = evaluate_objectives(env_name, grid, wL_grid)
        best_init = grid_np[torch.argmax(jF_grid)]

    # 2. SciPy L-BFGS-B Fine-Tuning
    def objective_and_gradient(x_np):
        x_tensor = torch.tensor(x_np, dtype=torch.float32, device=device, requires_grad=True).unsqueeze(0)
        wL = f(x_tensor).squeeze(0)
        if env_name == "groot": wL = torch.clamp(wL, -1.0, 4.0)
        jF, _ = evaluate_objectives(env_name, x_tensor, wL)
        loss = -jF.sum()

        # Use torch.autograd.grad to explicitly compute gradients
        grad_x = torch.autograd.grad(loss, x_tensor)[0]

        return loss.item(), grad_x.cpu().numpy().astype(np.float64).flatten()

    scipy_bounds = [(bnd[0], bnd[1])] * dim
    result = minimize(
        fun=objective_and_gradient, x0=best_init, method='L-BFGS-B',
        jac=True, bounds=scipy_bounds, options={'ftol': 1e-9, 'disp': False}
    )
    return result.x

def compute_true_baseline(env_name, gamma_func, wF_star, sigma_wF, sigma_wL, device):
    """High-precision numerical integration (10^5 samples) over follower's structural noise."""
    env = get_env_details(env_name)
    dim, bnd = env["dim"], env["bounds"]

    eps_wF = torch.randn((100000, dim), device=device) * sigma_wF
    # Fix: Ensure wF_star is float32 to match eps_wF and omega in gamma_func
    wF_exec = torch.clamp(torch.tensor(wF_star, dtype=torch.float32, device=device) + eps_wF, bnd[0], bnd[1]).to(torch.float32)

    with torch.no_grad():
        gamma_exec = gamma_func(wF_exec)
        expected_gamma = gamma_exec.mean().item()

    wF_s = wF_star[0] if dim == 1 else wF_star
    if env_name == "labor":
        return 3.0 * wF_s - expected_gamma
    elif env_name == "regulatory":
        return expected_gamma - (wF_s**2) - (sigma_wF**2)
    elif env_name == "exponential":
        return 5.0 * wF_s - expected_gamma
    elif env_name == "groot":
        gamma_clamp = torch.clamp(gamma_exec, -1.0, 4.0)
        expected_gamma_sq = (gamma_clamp**2).mean().item()
        return (wF_s - 5.0)**2 + sigma_wF**2 + expected_gamma_sq + sigma_wL**2
    elif env_name == "multitask":
        beta = np.array([2.0, 1.5, 3.0])
        return np.dot(wF_s, beta)

