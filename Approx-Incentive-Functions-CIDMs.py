# 1. Feature Map Generators & RKHS Sampler (M = 2D components)
# ------------------------------------------------------------------------------
def generate_rff_features(X, M, sigma, use_qmc=False, seed=42):
    """Generates finite feature map z(x) using MC or Owen-Scrambled QMC."""
    N, input_dim = X.shape
    D = M // 2
    if use_qmc:
        sobol = qmc.Sobol(d=input_dim, scramble=True, seed=seed)
        m_pow = math.ceil(math.log2(D))
        u_omega = torch.tensor(sobol.random_base2(m=m_pow)[:D], dtype=torch.float32)
        u_omega_clamped = torch.clamp(u_omega, 1e-6, 1.0 - 1e-6)
        # Map to spectral density via Inverse Normal CDF (Phi^-1)
        omega = (math.sqrt(2.0) * torch.erfinv(2.0 * u_omega_clamped - 1.0)) / sigma
        omega = omega.t()
    else:
        torch.manual_seed(seed)
        omega = torch.randn((input_dim, D), device=device) / sigma

    projection = torch.matmul(X, omega)
    Z = (1.0 / math.sqrt(D)) * torch.cat([torch.cos(projection), torch.sin(projection)], dim=1)
    return Z, omega

class RKHS_Sampler:
    """Samples standalone callable functions from the RKHS."""
    def __init__(self, M, sigma, input_dim, use_qmc):
        self.M, self.sigma, self.input_dim, self.use_qmc = M, sigma, input_dim, use_qmc
        self.seed_counter = 42

    def sample_function(self):
        dummy_X = torch.zeros((1, self.input_dim), device=device)
        _, omega = generate_rff_features(dummy_X, self.M, self.sigma, self.use_qmc, self.seed_counter)
        self.seed_counter += 1

        torch.manual_seed(self.seed_counter)
        w = torch.randn((self.M, 1), device=device)

        def f(x):
            if not isinstance(x, torch.Tensor):
                x = torch.tensor(x, dtype=torch.float32, device=device)
            if x.dim() == 1 and self.input_dim == 1:
                x = x.unsqueeze(-1)
            elif x.dim() == 1:
                x = x.unsqueeze(0)
            projection = torch.matmul(x, omega)
            Z = (1.0 / math.sqrt(self.M // 2)) * torch.cat([torch.cos(projection), torch.sin(projection)], dim=1)
            return torch.matmul(Z, w).squeeze(-1)
        return f

